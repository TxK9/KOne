function detectLocale() {
  try { const saved = localStorage.getItem(LOCALE_KEY); if (LOCALES.includes(saved)) return saved; } catch { /* storage unavailable */ }
  return /^zh(?:-|$)/i.test(globalThis.navigator?.language || '') ? 'zh-CN' : 'en';
}
