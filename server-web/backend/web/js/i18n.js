/** Audit titles establish the semantic context; free-text details stay byte-for-byte intact. */
export function recordDetail(record) {
  const value = record.detail || '';
  if (record.title === '节点执行结果') {
    const index = value.lastIndexOf(' / ');
    if (index !== -1) return value.slice(0, index + 3) + systemText(value.slice(index + 3), '系统消息不可用');
  }
  if (record.title === '分配线路') {
    const match = value.match(/^(.* \/ )(\d+) 位用户$/s);
    if (match) return match[1] + count(Number(match[2]), 'customer');
  }
  // Assignment summaries retain user/profile names. Only the generated final count changes.
  if (record.title === '分配配置') return value.replace(/ 等 (\d+) 位用户$/, (_, n) => isChinese ? ' 等 ' + number(Number(n)) + ' 位用户' : ' (' + count(Number(n), 'customer') + ' total)');
  return value;
}
